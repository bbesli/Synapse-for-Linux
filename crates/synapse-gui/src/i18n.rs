impl Strings {
    pub fn get(lang: Language) -> &'static Strings {
        match lang.resolve() {
            Language::Tr => &TR,
            _ => &EN,
        }
    }

    /// `76%` in English, `%76` in Turkish.
    pub fn percent(&self, value: u8) -> String {
        match self.lang {
            Language::Tr => format!("%{value}"),
            _ => format!("{value}%"),
        }
    }

    pub fn preset(&self, preset: HardwarePreset) -> String {
        match preset {
            HardwarePreset::Music => self.preset_music.into(),
            HardwarePreset::Game => self.preset_game.into(),
            HardwarePreset::Movie => self.preset_movie.into(),
            HardwarePreset::Flat => self.preset_flat.into(),
            HardwarePreset::Custom => self.preset_custom.into(),
            HardwarePreset::Unknown(raw) => format!("0x{raw:02X}"),
        }
    }

    pub fn led(&self, mode: LedMode) -> String {
        match mode {
            LedMode::Link => self.led_link.into(),
            LedMode::Battery => self.led_battery.into(),
            LedMode::Warning => self.led_warning.into(),
            LedMode::Off => self.led_off.into(),
            LedMode::Unknown(raw) => format!("{raw}"),
        }
    }

    pub fn curve_name(&self, curve: &BuiltinCurve) -> &'static str {
        match self.lang {
            Language::Tr => curve.name_tr,
            _ => curve.name_en,
        }
    }

    /// Slider showing a percentage in the language's order (`%20` / `20 %`).
    pub fn percent_slider<'a>(&self, value: &'a mut u8, range: std::ops::RangeInclusive<u8>) -> egui::Slider<'a> {
        let slider = egui::Slider::new(value, range).step_by(5.0);
        match self.lang {
            Language::Tr => slider.prefix("%"),
            _ => slider.suffix("%"),
        }
    }

    pub fn minutes(&self, minutes: u8) -> String {
        if minutes == 0 {
            self.never.into()
        } else {
            format!("{minutes} {}", self.minutes_short)
        }
    }
}

